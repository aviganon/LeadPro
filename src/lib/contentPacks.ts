// חבילות תוכן מוכנות לקורסים. מפתח = מספר קורס.
// כל חבילה: שאלות (חידון), כרטיסיות, זוגות זיכרון, וחומרי עזר.
// מיובאות לקורס דרך הניהול (כפתור "ייבא תוכן") → /api/admin/import-content.

export interface PackQuestion {
  prompt: string
  options: string[]
  answer: string       // חייב להיות זהה לאחת האפשרויות
  explanation?: string
  difficulty?: 1 | 2 | 3   // 1=קל, 2=בינוני, 3=קשה (ברירת מחדל: 2)
  examPaper?: string       // למבחנים אמיתיים — מזהה מבחן המקור (למשל "קיץ 2002")
  needsReview?: boolean    // תשובה לא ודאית — תיובא מוסתרת ותופיע בניהול לעריכה
  topic?: string           // נושא לקיבוץ בניהול
}
export interface PackCard { front: string; back: string }
export interface PackPair { a: string; b: string }
export interface PackMaterial { title: string; bodyMarkdown: string }

export interface ContentPack {
  title: string
  questions: PackQuestion[]        // שאלות תרגול (אימון חופשי)
  examQuestions?: PackQuestion[]   // מאגר מבחן אמיתי (משרד החינוך) — נטען בנפרד למצב "מבחן"
  flashcards: PackCard[]
  memory: PackPair[]
  materials: PackMaterial[]
}

